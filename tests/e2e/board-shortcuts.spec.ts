import { test, expect } from '@playwright/test'

test('Tab cycles friendly active units only on the board and Escape lets focus leave', async ({ page }) => {
	await page.goto('/play/1/')
	const origin = page.locator('[data-cell="1"]')
	const selected = page.locator('.board [aria-pressed="true"]')
	await origin.click()
	await expect(origin).toBeFocused()
	await page.keyboard.press('Tab')
	await expect(origin).toHaveAttribute('aria-pressed', 'false')
	await expect(selected).toHaveCount(1)
	await expect(selected).toBeFocused()
	await page.keyboard.press('Shift+Tab')
	await expect(origin).toHaveAttribute('aria-pressed', 'true')
	await expect(origin).toBeFocused()
	// Space remains capture: move onto the adjacent hospital, then capture it.
	await page.keyboard.press('ArrowDown')
	await page.keyboard.press('Space')
	await expect(page.locator('[data-cell="9"]')).toHaveClass(/-halfcaptured/)
	await page.keyboard.press('Escape')
	await expect(selected).toHaveCount(0)
	await page.keyboard.press('Escape')
	await expect(page.getByRole('button', { name: 'End round', exact: true })).toBeFocused()
	await page.getByRole('button', { name: 'Options and help', exact: true }).click()
	const options = page.getByRole('dialog', { name: 'Options and help', exact: true })
	await page.keyboard.press('Tab')
	await expect(selected).toHaveCount(0)
	expect(await options.evaluate((element) => element.contains(document.activeElement))).toBe(true)
	await page.keyboard.press('End')
	await expect(page.locator('.turn-details strong')).toHaveText('Round 1')
})

test('End uses the same optional confirmation as the button and ignores modified or repeated keys', async ({ page, context, baseURL }) => {
	await context.addCookies([{ name: 'pixelswars-settings', value: encodeURIComponent(JSON.stringify({ confirmEndTurn: true })), url: baseURL! }])
	await page.goto('/play/1/')
	const origin = page.locator('[data-cell="1"]')
	const warning = page.getByRole('dialog', { name: 'End round', exact: true })
	await origin.click()
	await origin.dispatchEvent('keydown', { key: 'End', ctrlKey: true, bubbles: true })
	await origin.dispatchEvent('keydown', { key: 'End', repeat: true, bubbles: true })
	await expect(warning).toHaveCount(0)
	await page.keyboard.press('End')
	await expect(warning).toBeVisible()
	await warning.getByRole('button', { name: 'No', exact: true }).click()
	await expect(page.locator('.turn-details strong')).toHaveText('Round 1')
	await origin.focus()
	await page.keyboard.press('End')
	await warning.getByRole('button', { name: 'Yes', exact: true }).click()
	await expect(page.locator('.turn-details strong')).toHaveText('Round 2')
})
