import { test, expect } from '@playwright/test'

test('void brush removes aircraft, rejects placement and preserves mirrored cutouts after reload and export', async ({ page }) => {
	await page.goto('/map-editor/')
	await expect.poll(() => page.evaluate(() => localStorage.getItem('pixelswar-map-editor-draft-v1'))).not.toBeNull()
	await page.locator('#columns').fill('3')
	await page.locator('#rows').fill('3')
	await page.locator('#new').click()
	await page.locator('#mirror-mode').selectOption('rotation')
	const cell = (index: number) => page.locator(`#board [data-cell="${index}"]`)
	await page.locator('[data-brush="plane"]').click()
	await cell(0).press('Enter')
	await expect(page.locator('#board img')).toHaveCount(2)
	await page.getByRole('button', { name: 'Void', exact: true }).click()
	await cell(0).press('Enter')
	await expect(page.locator('#board img')).toHaveCount(0)
	for (const index of [0, 8]) {
		await expect(cell(index)).toHaveClass(/-void/)
		await expect(cell(index)).toHaveCSS('background-color', 'rgb(17, 26, 20)')
		await expect(cell(index)).toHaveCSS('background-image', 'none')
	}
	await page.locator('[data-brush="plane"]').click()
	await cell(0).press('Enter')
	await expect(page.locator('#status')).toHaveText('No unit can be placed on a void tile.')
	await page.reload()
	await expect(cell(0)).toHaveClass(/-void/)
	await expect(cell(8)).toHaveClass(/-void/)
	await page.locator('#json-panel summary').click()
	await expect(page.locator('#json-output')).toHaveValue(/"cells"/)
	const exported = JSON.parse(await page.locator('#json-output').inputValue())
	expect(exported.cells[0]).toEqual({ classes: ['-void'], owner: 0, capturePoints: 20 })
	expect(exported.cells[8]).toEqual(exported.cells[0])
	expect(exported.units).toEqual([])
	await page.goto('/')
	await expect(page.getByRole('heading', { name: 'Void', exact: true })).toHaveCount(0)
})
