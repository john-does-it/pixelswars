test('combat updates rune-driven health, locks controls and clears a dead attacker', async ({ page }) => {
	const errors: string[] = []
	page.on('pageerror', (error) => errors.push(error.message))
	await page.goto('/play/1/')
	const cell = (index: number) => page.locator(`[data-cell="${index}"]`)
	const end = page.getByRole('button', { name: 'End round', exact: true })
	await cell(2).click()
	await cell(10).click()
	await cell(18).click()
	await cell(26).click()
	await end.click()
	await cell(58).click()
	await cell(50).click()
	await cell(42).click()
	await end.click()
	await cell(26).click()
	await cell(34).click()
	await expect(cell(42).getByAltText('Attack target')).toBeVisible()
	await cell(42).click()
	await expect(end).toBeDisabled()
	await expect(cell(42).locator('[data-unit]')).toHaveAttribute('data-health', '164')
	await expect(cell(34).locator('[data-unit]')).toHaveCount(0)
	await expect(end).toBeEnabled()
	await expect(page.getByRole('button', { name: 'Confirm move', exact: true })).toBeDisabled()
	await expect(page.locator('[data-unit]')).toHaveCount(9)
	expect(errors).toEqual([])
})

test('keyboard movement leaves no focused cell after confirming or cancelling', async ({ page }) => {
	await page.goto('/play/1/')
	const origin = page.locator('[data-cell="1"]')
	const destination = page.locator('[data-cell="9"]')
	await origin.click()
	await origin.press('ArrowDown')
	await expect(destination).toBeFocused()
	await destination.press('Enter')
	await expect(page.locator('[data-cell]:focus')).toHaveCount(0)
	await expect(page.locator('[aria-pressed="true"][data-cell]')).toHaveCount(0)
	await destination.click()
	await destination.press('ArrowDown')
	await page.keyboard.press('Escape')
	await expect(page.locator('[data-cell]:focus')).toHaveCount(0)
	await expect(destination.locator('[data-unit]')).toBeVisible()
})

test('captured airport offers aircraft and buys a plane after the tile is freed', async ({ page }) => {
	await page.goto('/play/2/')
	const cell = (i: number) => page.locator('[data-cell="' + i + '"]')
	const end = () => page.getByRole('button', { name: 'End round', exact: true }).click()
	const next = async () => {
		await end()
		await end()
	}
	const capture = () => page.getByRole('button', { name: 'Capture', exact: true }).click()
	await cell(2).click()
	await cell(14).click()
	await capture()
	await next()
	await cell(14).click()
	await capture()
	for (const i of [26, 27, 28, 29, 30]) await cell(i).click()
	await next()
	await cell(30).click()
	await cell(42).click()
	await capture()
	await next()
	await cell(42).click()
	await capture()
	await cell(42).click()
	await expect(page.getByRole('dialog', { name: 'Airport', exact: true })).toBeVisible()
	await expect(page.getByText('Free this airport to build a unit').first()).toBeVisible()
	await page.getByRole('button', { name: 'Close', exact: true }).click()
	await cell(42).click()
	await cell(43).click()
	await page.getByRole('button', { name: 'Confirm move', exact: true }).click()
	await cell(42).click()
	await expect(page.getByRole('dialog', { name: 'Airport', exact: true })).toBeVisible()
	await expect(page.getByRole('button', { name: 'Buy Infantry', exact: true })).toHaveCount(0)
	await expect(page.getByRole('button', { name: 'Buy Helicopter', exact: true })).toBeDisabled()
	await expect(page.getByRole('button', { name: 'Buy Plane', exact: true })).toBeDisabled()
	await page.getByRole('button', { name: 'Close', exact: true }).click()
	for (let i = 0; i < 15; i++) await next()
	await cell(42).click()
	await page.getByRole('button', { name: 'Buy Plane', exact: true }).click()
	await expect(page.getByRole('dialog')).toHaveCount(0)
	await expect(cell(42)).toHaveAttribute('aria-label', /plane/)
})
