import { test, expect } from '@playwright/test'

test('mission permits a full battle with capture, recruitment and a naval crossing', async ({ page }) => {
	test.setTimeout(90000)
	await page.goto('/tutorial/')
	const cell = (index: number) => page.locator(`[data-cell="${index}"]`)
	const guide = page.locator('.tutorial-guide')
	const end = async () => {
		await page.getByRole('button', { name: 'End round', exact: true }).click()
		await expect(page.getByRole('button', { name: 'End round', exact: true })).toBeEnabled()
	}
	const capture = () => page.getByRole('button', { name: 'Capture', exact: true }).click()
	await expect(guide).toHaveAttribute('data-step', 'foothold')
	await expect(page.locator('.board [data-unit]')).toHaveCount(4)
	await expect(page.getByRole('button', { name: 'End round', exact: true })).toBeEnabled()
	await cell(16).click()
	await cell(17).click()
	await capture()
	await cell(7).click()
	await expect(page.getByRole('button', { name: 'End round', exact: true })).toBeEnabled()
	await cell(7).click()
	await expect(page.locator('#tutorial-instruction')).toContainText('no shots left')
	await end()
	await expect(page.getByText('Round 3', { exact: true })).toBeVisible()
	await cell(17).click()
	await capture()
	await expect(guide).toHaveAttribute('data-step', 'hold')
	await expect(cell(34).locator('[data-unit]')).toBeVisible()
	await cell(11).click()
	await page.getByRole('button', { name: 'Buy Infantry', exact: true }).click()
	await expect(cell(11).locator('[data-unit]')).toBeVisible()
	await cell(12).click()
	await cell(24).click()
	await cell(34).click()
	await expect(cell(12).locator('[data-unit]')).toHaveCount(0)
	await expect(page.locator('#tutorial-instruction')).toContainText('Open Passengers')
	await cell(44).click()
	await page.getByRole('button', { name: /Passengers/ }).click()
	await page.locator('.passenger').first().click()
	await cell(54).click()
	await expect(cell(54).locator('[data-unit]')).toBeVisible()
	await end()
	await expect(guide).toHaveAttribute('data-step', 'cross')
	await cell(54).click()
	await cell(64).click()
	await capture()
	await end()
	await cell(64).click()
	await capture()
	await expect(guide).toHaveAttribute('data-completed', 'true')
	await expect(page.locator('#tutorial-instruction')).toContainText('Mission complete')
	await expect(page.getByRole('button', { name: 'End round', exact: true })).toBeEnabled()
})

test('movement and undo stay free and keyboard inputs are not tied to lesson steps', async ({ page }) => {
	await page.goto('/tutorial/')
	const cell = (index: number) => page.locator(`[data-cell="${index}"]`)
	await cell(12).click()
	await cell(12).focus()
	await page.keyboard.press('ArrowUp')
	await expect(cell(2).locator('[data-unit]')).toBeVisible()
	await expect(page.locator('#tutorial-instruction img')).toHaveCount(2)
	await page.keyboard.press('Escape')
	await expect(cell(12).locator('[data-unit]')).toBeVisible()
	await cell(12).click()
	await cell(22).click()
	await page.getByRole('button', { name: 'Confirm move', exact: true }).click()
	await expect(cell(22).locator('[data-unit]')).toBeVisible()
	await expect(page.locator('.tutorial-guide')).toHaveAttribute('data-step', 'foothold')
	await expect(page.getByRole('button', { name: 'End round', exact: true })).toBeEnabled()
})

test('mission restart, command reminders and legacy links fit small screens', async ({ page }) => {
	await page.setViewportSize({ width: 320, height: 640 })
	await page.goto('/tutorial/capture/')
	await expect(page).toHaveURL(/\/tutorial\/$/)
	const guide = page.locator('.tutorial-guide')
	const height = (await guide.boundingBox())!.height
	const commands = page.getByRole('button', { name: 'Commands', exact: true })
	await commands.click()
	const dialog = page.getByRole('dialog', { name: 'Commands', exact: true })
	await expect(dialog).toBeVisible()
	await expect(dialog.locator('img').first()).toBeVisible()
	expect((await guide.boundingBox())!.height).toBe(height)
	await page.keyboard.press('Escape')
	await expect(dialog).toHaveCount(0)
	await expect(commands).toBeFocused()
	await page.getByRole('button', { name: 'Restart training', exact: true }).click()
	await expect(guide).toHaveAttribute('data-step', 'foothold')
	await expect(guide.locator('details')).toHaveCount(0)
	expect(await guide.evaluate((element) => element.scrollTop)).toBe(0)
	await expect(page.locator('.board [data-unit]')).toHaveCount(4)
	expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
	expect((await page.locator('.board-viewport').boundingBox())!.height).toBeGreaterThan(150)
	await page.screenshot({ path: 'tmp/tutorial-mission-mobile.png' })
})
