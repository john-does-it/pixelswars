import { test, expect } from '@playwright/test'
import { openMapFilters } from './filter-helpers'

test('map filters combine size and tags, recover from empty results and open a match', async ({ page }) => {
	await page.goto('/')
	await openMapFilters(page)
	const cards = page.locator('a.map')
	const total = await cards.count()
	const filters = page.getByRole('group', { name: 'Filter maps', exact: true })
	const sizes = filters.getByRole('group', { name: 'Size', exact: true })
	const xxs = sizes.getByRole('checkbox', { name: 'XXS', exact: true })
	const xs = sizes.getByRole('checkbox', { name: 'XS', exact: true })
	const symmetrical = filters.getByRole('checkbox', { name: 'Symmetrical', exact: true })
	const mobile = filters.getByRole('checkbox', { name: 'Mobile friendly', exact: true })
	const reset = filters.getByRole('button', { name: 'Reset filters' })
	await expect(reset).toBeDisabled()
	await expect(reset.locator('img')).toHaveAttribute('src', /\/previous-action\.svg$/)
	await xxs.check()
	await expect(cards).toHaveCount(3)
	await expect(cards.getByRole('heading')).toHaveText(['Gentle Slope', 'Neighbor Trouble', 'Neighbors’ Square'])
	await xs.check()
	await expect(cards).toHaveCount(5)
	await expect(cards.getByRole('heading')).toHaveText(['Gentle Slope', 'Neighbor Trouble', 'Neighbors’ Square', 'A Little Detour', 'Not the Shoes!'])
	await xs.uncheck()
	await symmetrical.check()
	await expect(cards).toHaveCount(2)
	await xxs.uncheck()
	await sizes.getByRole('checkbox', { name: 'XXL', exact: true }).check()
	await mobile.check()
	await expect(cards).toHaveCount(0)
	await expect(page.getByText('No maps match these filters.', { exact: false })).toBeVisible()
	await sizes.getByRole('checkbox', { name: 'XXL', exact: true }).uncheck()
	await xs.check()
	await xxs.uncheck()
	await mobile.check()
	await expect(cards).toHaveCount(2)
	await expect(cards.getByRole('heading')).toHaveText(['A Little Detour', 'Not the Shoes!'])
	await expect(page.locator('.filter-results')).toHaveText(`2 maps out of ${total}`)
	await xs.uncheck()
	await expect(cards).toHaveCount(5)
	await mobile.uncheck()
	expect(await cards.count()).toBeGreaterThan(1)
	for (const card of await cards.all()) {
		await expect(card.getByLabel('Symmetrical: Yes', { exact: true })).toBeVisible()
	}
	await reset.click()
	await expect(cards).toHaveCount(total)
	await expect(sizes.locator('input:checked')).toHaveCount(0)
	await expect(symmetrical).not.toBeChecked()
	await expect(mobile).not.toBeChecked()
	await expect(reset).toBeDisabled()
	await mobile.check()
	await expect(page.locator('a.map[href$="/play/8/"]')).toBeVisible()
	await expect(page.locator('a.map[href$="/play/15/"]')).toHaveCount(0)
	await xxs.check()
	await reset.click()
	await expect(cards).toHaveCount(total)
	await expect(xxs).not.toBeChecked()
	await page.setViewportSize({ width: 320, height: 740 })
	await openMapFilters(page)
	expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
	await xs.check()
	await cards.first().click()
	await expect(page.getByRole('dialog')).toBeVisible()
})

test('filter links survive reload and returning from a match without losing unrelated URL state', async ({ page }) => {
	await page.goto('/?size=XS,unknown,XS&symmetrical=1&campaign=friend#maps')
	await openMapFilters(page)
	const filters = page.getByRole('group', { name: 'Filter maps', exact: true })
	const xs = filters.getByRole('checkbox', { name: 'XS', exact: true })
	const xxs = filters.getByRole('checkbox', { name: 'XXS', exact: true })
	const symmetrical = filters.getByRole('checkbox', { name: 'Symmetrical', exact: true })
	const all = filters.getByRole('button', { name: 'All sizes', exact: true })
	const cards = page.locator('a.map')
	await expect(xs).toBeChecked()
	await expect(symmetrical).toBeChecked()
	await expect(cards).toHaveCount(2)
	await expect(all).toHaveAttribute('aria-pressed', 'false')
	await xxs.focus()
	await xxs.press('Space')
	await expect(xxs).toBeChecked()
	expect(new URL(page.url()).searchParams.get('size')).toBe('XXS,XS')
	await page.reload()
	await openMapFilters(page)
	await expect(xxs).toBeChecked()
	await expect(xs).toBeChecked()
	await cards.first().click()
	await page.getByRole('link', { name: 'Play with someone on this device', exact: true }).click()
	await expect(page.locator('.board')).toBeVisible()
	await page.goBack()
	await openMapFilters(page)
	await expect(xxs).toBeChecked()
	await expect(xs).toBeChecked()
	await expect(symmetrical).toBeChecked()
	await all.click()
	await expect(all).toHaveAttribute('aria-pressed', 'true')
	await expect(xs).not.toBeChecked()
	await expect(xxs).not.toBeChecked()
	await expect(symmetrical).toBeChecked()
	await filters.getByRole('button', { name: 'Reset filters' }).click()
	const url = new URL(page.url())
	expect(url.search).toBe('?campaign=friend')
	expect(url.hash).toBe('#maps')
	await page.goto('/?size=invalid&mobile=invalid')
	await openMapFilters(page)
	await expect(all).toHaveAttribute('aria-pressed', 'true')
	await expect(filters.getByRole('button', { name: 'Reset filters' })).toBeDisabled()
})

test('mobile filter panel starts collapsed and reports selections without hiding results', async ({ page }) => {
	await page.setViewportSize({ width: 320, height: 740 })
	await page.goto('/?size=XXS,XS&mobile=1#maps')
	const toggle = page.getByRole('button', { name: 'Filters · 3', exact: true })
	await expect(toggle).toHaveAttribute('aria-expanded', 'false')
	await expect(page.locator('#map-filter-options')).toBeHidden()
	await expect(page.locator('a.map')).toHaveCount(5)
	await toggle.click()
	await expect(toggle).toHaveAttribute('aria-expanded', 'true')
	await expect(page.getByRole('checkbox', { name: 'XS', exact: true })).toBeChecked()
	await toggle.click()
	await page.getByRole('button', { name: 'Reset filters', exact: true }).click()
	await expect(page.getByRole('button', { name: 'Filters · 0', exact: true })).toHaveAttribute('aria-expanded', 'false')
	await expect(page.locator('a.map')).toHaveCount(26)
	expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
	await page.setViewportSize({ width: 1280, height: 900 })
	await expect(page.locator('#map-filter-options')).toBeVisible()
	await expect(page.getByRole('button', { name: 'Filters · 0' })).toBeHidden()
})
