import { test, expect } from '@playwright/test'
import { readMapFixture } from '../map-fixtures'
import { readMap } from '../../src/lib/map-editor/model.ts'

test('imports a map, saves a named local copy and launches it from the editor and gallery', async ({ page }) => {
	await page.goto('/#editor-title')
	const editor = page.locator('.map-editor')
	const input = editor.locator('input[type=file]')
	await input.setInputFiles({ name: 'broken.json', mimeType: 'application/json', buffer: Buffer.from('{') })
	await expect(editor.getByRole('alert')).toContainText('valid JSON')
	await expect(editor.locator('[data-cell]')).toHaveCount(425)
	const fixture = readMapFixture(1)
	const fileChooser = page.waitForEvent('filechooser')
	await editor.getByRole('button', { name: 'Import', exact: true }).click()
	await (await fileChooser).setFiles({ name: 'map.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(fixture)) })
	await expect(editor.locator('[data-cell]')).toHaveCount(fixture.cells.length)
	await editor.getByRole('button', { name: 'Save map' }).click()
	const dialog = page.getByRole('dialog')
	await dialog.getByLabel('Name', { exact: true }).fill('  Backwater  ')
	await dialog.getByRole('button', { name: 'Confirm', exact: true }).click()
	await expect(dialog).toHaveAccessibleName('Backwater saved')
	await dialog.getByRole('button', { name: 'Continue editing' }).click()
	await editor.getByRole('button', { name: 'Save map' }).click()
	await dialog.getByRole('button', { name: 'Confirm', exact: true }).click()
	await dialog.getByRole('button', { name: 'Play this map' }).click()
	await dialog.getByRole('link', { name: 'Play with someone on this device' }).click()
	await expect(page.locator('.board [data-cell]')).toHaveCount(fixture.cells.length)
	await expect(page).toHaveTitle(/Backwater/)
	await page.reload()
	await expect(page.locator('.board')).toBeVisible()
	await page.goto('/')
	await page.getByRole('button', { name: 'View all maps' }).click()
	const card = page.getByRole('link', { name: 'Backwater', exact: true })
	await expect(card).toHaveCount(1)
	await expect(card.locator('.cell-container')).toHaveCount(fixture.cells.length)
	await card.click()
	await page.getByRole('link', { name: 'Backwater', exact: true }).click()
	await dialog.getByRole('button', { name: 'Play against AI' }).click()
	await dialog.getByRole('link', { name: 'Easy', exact: true }).click()
	await expect(page.locator('.board')).toBeVisible()
	await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('pixelswars-saved-match') ?? 'null')?.map.name)).toBe('Backwater')
	await page.goto('/')
	await page.getByRole('link', { name: 'Resume match' }).click()
	await expect(page).toHaveTitle(/Backwater/)
	await expect(page.locator('.board')).toBeVisible()
})

test('an unfinished named map can be reopened and completed in the editor', async ({ page }) => {
	await page.goto('/#editor-title')
	const editor = page.locator('.map-editor')
	const dialog = page.getByRole('dialog')
	await editor.getByRole('button', { name: 'Save map' }).click()
	await expect(dialog.getByRole('button', { name: 'Confirm' })).toBeDisabled()
	await dialog.getByLabel('Name', { exact: true }).fill('Work in progress')
	await dialog.getByRole('button', { name: 'Confirm' }).click()
	await expect(dialog.getByRole('button', { name: 'Play this map' })).toBeDisabled()
	await dialog.getByRole('button', { name: 'Continue editing' }).click()
	await editor.getByRole('button', { name: 'Reset' }).click()
	await page.reload()
	await page.getByRole('button', { name: 'View all maps' }).click()
	await page.getByRole('link', { name: 'Work in progress', exact: true }).click()
	await page.locator('.featured .selected').click()
	await dialog.getByRole('button', { name: 'Edit this map' }).click()
	await editor.locator('#unit-picker-1').selectOption('infantry')
	await editor.locator('[data-cell="0"]').press('Enter')
	await editor.locator('#unit-picker-2').selectOption('infantry')
	await editor.locator('[data-cell="2"]').press('Enter')
	await editor.getByRole('button', { name: 'Save map' }).click()
	await expect(dialog.getByLabel('Name', { exact: true })).toHaveValue('Work in progress')
	await dialog.getByRole('button', { name: 'Confirm' }).click()
	await expect(dialog.getByRole('button', { name: 'Play this map' })).toBeEnabled()
})

test('separate sprite pickers paint units and buildings with their own colors', async ({ page }) => {
	await page.goto('/#editor-title')
	await expect(page.locator('.sprite-picker')).toHaveCount(6)
	for (const side of [2, 1, 0]) {
		await page.locator('#building-picker-' + side).selectOption('building_city')
		const cell = page.locator('[data-cell="0"]')
		await cell.click()
		await expect(cell).toHaveClass(/-city/)
		if (side) await expect(cell).toHaveClass(new RegExp('-capturedby' + side))
		else await expect(cell).not.toHaveClass(/-capturedby/)
	}
})

test('paint, undo, restore and export a map from the homepage', async ({ page }) => {
	await page.goto('/#editor-title')
	const cell = page.locator('#board [data-cell="0"]')
	await page.locator('.terrain-picker').selectOption('terrain_road')
	await cell.press('Enter')
	await cell.press('Control+z')
	await expect(cell).not.toHaveClass(/-road/)
	await cell.press('Enter')
	await page.reload()
	await expect(cell).toHaveClass(/-road/)
	const download = page.waitForEvent('download')
	await page.getByRole('button', { name: 'Export', exact: true }).click()
	const stream = await (await download).createReadStream()
	let json = ''
	for await (const chunk of stream!) json += chunk
	const exported = JSON.parse(json)
	expect(readMap(JSON.stringify(exported)).cells[0].classes).toContain('-road')
})
